#!/bin/bash
# set-road.sh — the budget road's single writer (designs/budget-road.md § Verbs).
#
#   set-road.sh show                                  the road in order, each arc's lane and admission
#   set-road.sh focus <arc> [--summary T]             draw an arc to the head of the pinned list
#   set-road.sh unpin <arc>                           leave it on the road, ordered by recency
#   set-road.sh add <arc> --summary T                 a new arc, unpinned
#   set-road.sh drop <arc>                            take an arc off the road (discretion only)
#   set-road.sh alias <old> <arc|->                   fold a retired arc into another (- = unarced)
#   set-road.sh lanes <primary> <secondary>           lane shares, summing to 1
#   set-road.sh init [--from-slate [--pin a,b,…]] [< road.json]
#                                                     write the whole road, retiring the old slate
#
# Every writer verb requires --authorized-by <login> on maintainers/allowlist and
# takes --note "<the maintainer's words>" and --message-id <id>. --dry-run prints
# the resulting allocation/ files (and, for init, the slate files it would
# remove) without pushing. Each write is one CAS commit to journal2 that also
# regenerates allocation/mandate.md (the foreman's priority mandate) and
# allocation/README.md (the road rendered for people).
#
# init removes config/apportionment, config/foreman-mandate, and every schema-2
# config/arc-budgets/<arc> in the SAME commit; schema-1 rolling arcs stay.
# Rollback is `git revert` of that commit on journal2.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/common.sh"
export GARDEN_TAG="set-road"
command -v jq >/dev/null 2>&1 || die "set-road.sh needs jq"

usage() { sed -n '2,23p' "$0"; }
verb="${1:-}"; [ -n "$verb" ] || { usage; exit 2; }
shift
authorized_by=""; message_id=""; note=""; summary=""; dry_run=0; from_slate=0
pins="minion-town-claude-api,minion-town-mcp-ocapn,minion-town-git-remote,minion-town-ui"
args=()
while [ $# -gt 0 ]; do
  case "$1" in
    --authorized-by) authorized_by="${2:?--authorized-by needs a login}"; shift 2 ;;
    --message-id) message_id="${2:?--message-id needs a value}"; shift 2 ;;
    --note) note="${2?--note needs text}"; shift 2 ;;
    --summary) summary="${2?--summary needs text}"; shift 2 ;;
    --from-slate) from_slate=1; shift ;;
    --pin) pins="${2?--pin needs a comma list}"; shift 2 ;;
    --dry-run) dry_run=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) die "unknown option: '$1'" ;;
    *) args+=("$1"); shift ;;
  esac
done

arc_ok() { [[ "$1" =~ ^[a-z0-9][a-z0-9-]*$ ]] || die "illegal arc name '$1'"; }
need() { [ "${#args[@]}" -eq "$1" ] || die "$verb takes $1 argument(s)"; }
case "$verb" in
  show) need 0 ;;
  focus|unpin|drop) need 1; arc_ok "${args[0]}" ;;
  add) need 1; arc_ok "${args[0]}"; [ -n "$summary" ] || die "add needs --summary" ;;
  alias) need 2; arc_ok "${args[0]}"; [ "${args[1]}" = - ] || arc_ok "${args[1]}" ;;
  lanes) need 2
    for s in "${args[@]}"; do [[ "$s" =~ ^(0([.][0-9]+)?|1([.]0+)?|[.][0-9]+)$ ]] || die "lane share '$s' is not in [0, 1]"; done
    awk -v a="${args[0]}" -v b="${args[1]}" 'BEGIN { d = a + b - 1; if (d < 0) d = -d; exit !(d < 1e-9) }' \
      || die "lane shares must sum to 1" ;;
  init) need 0 ;;
  *) usage; die "unknown verb '$verb'" ;;
esac

DIR="${GARDEN_ROAD_CLONE:-${GARDEN_PRODUCER_CLONE:-$GARDEN_STATE/producer/journal}}"
ROAD="allocation/road.json"
by="${GARDEN_SENDER:-${GARDEN_JOB_BASE:-set-road}}"

# road_show <dir> — the road for people: lanes, then each arc in order.
road_show() {
  local dir="$1" out
  out="$(budget_road "$dir")"
  if [ ! -f "$dir/$ROAD" ]; then
    printf 'No road yet (allocation/road.json absent): no lanes; the arcs share discretion.\n'
  fi
  awk -F'\t' '$1 == "pool" {
      printf "pool %s: u=%s t=%s R_k=%s lanes=%s D=%s (at reset %s) verdict=%s%s resets %s\n",
        $2, $4, $3, $8, $9, $10, $13, $11, ($12 == "-" ? "" : "/" $12), $19 }' <<<"$out"
  road_arc_admission "$dir" | awk -F'\t' '$2 != "*" {
      printf "%2s. %-32s %-9s %-10s %s\n", $1, $2, ($3 == "-" ? "" : $3), $4,
        ($5 > 0 ? $6 : "(no planned work)" ($6 == "" ? "" : " " $6)) }'
  return 0
}

# render <dir> — regenerate allocation/{mandate,README}.md from road.json.
render() {
  local dir="$1" f="$1/$ROAD"
  jq -r '
    "# Generated by set-road.sh from allocation/road.json; do not hand-edit.",
    "# Change the road through the liaison (say \"focus <arc>\").",
    "",
    "Work the road in order. The primary and secondary lanes go to the first two",
    "arcs below with planned work; arcs without a lane draw on discretion.",
    "",
    (if (.notes // "") != "" then (.notes, "") else empty end),
    ((.pinned // []) as $p | (.arcs // []) | to_entries[]
      | .value.arc as $a
      | "\(.key + 1). \($a)\(if ($p | index($a)) != null then " (pinned)" else "" end): \(.value.summary // "")")
  ' "$f" > "$dir/allocation/mandate.md"
  jq -r '
    "# The budget road",
    "",
    "Generated by `scripts/jobs/set-road.sh` from `allocation/road.json`; do not hand-edit.",
    "Design: designs/budget-road.md. `git log -- allocation` is the record of the maintainer'"'"'s focus.",
    "",
    "Lanes: " + ((.lanes // {}) | to_entries | map("\(.key) \(.value)") | join(", ")) + ".",
    "",
    "| # | Arc | Pinned | Summary |",
    "| --- | --- | --- | --- |",
    ((.pinned // []) as $p | (.arcs // []) | to_entries[]
      | .value.arc as $a
      | "| \(.key + 1) | `\($a)` | \(if ($p | index($a)) != null then "yes" else "" end) | \(.value.summary // "" | gsub("\\|"; "\\\\|")) |"),
    "",
    (if ((.aliases // {}) | length) > 0 then
      ("Aliases: " + ((.aliases) | to_entries | map("`\(.key)` → \(if .value == null then "unarced" else "`\(.value)`" end)") | join(", ")) + ".", "")
     else empty end),
    "Set by \(.set_by // "?") at \(.set_at // "?"), authorized by \(.authorized_by // "?")."
  ' "$f" > "$dir/allocation/README.md"
}

# from_slate <dir> — a road.json derived from the live slate.
from_slate() {
  local dir="$1" arcs
  arcs="$(for f in "$dir"/config/arc-budgets/*; do
      [ -f "$f" ] || continue
      jq -c 'select(.schema == 2 and .status == "active")' "$f" 2>/dev/null || true
    done | jq -sc 'sort_by(.rank) | map(select(.arc != "unallocated") | {arc, summary: (.summary // "")})')"
  [ -n "$arcs" ] || arcs='[]'
  jq -n --argjson arcs "$arcs" --arg pins "$pins" '
    ($pins | split(",") | map(select(. != ""))) as $p
    | ($p | map(. as $x | ($arcs | map(select(.arc == $x)) | .[0]) // {arc: $x, summary: ""})) as $head
    | {schema: 1, lanes: {primary: 0.6, secondary: 0.4}, pinned: $p,
       arcs: ($head + ($arcs | map(select(.arc as $a | $p | index($a) | not)))),
       aliases: {unallocated: null}}'
}

# validate <json> — the road.json shape.
validate() {
  jq -e '
    (.schema == 1)
    and ((.lanes // {primary: 0.6, secondary: 0.4}) | type == "object"
         and (to_entries | all(.value | type == "number" and . >= 0 and . <= 1))
         and ((to_entries | map(.value) | add) as $s | ($s - 1) | fabs < 1e-9))
    and (.arcs | type == "array" and all(.arc | type == "string" and test("^[a-z0-9][a-z0-9-]*$")))
    and ((.arcs | map(.arc) | unique | length) == (.arcs | length))
    and ((.pinned // []) as $p | (.arcs | map(.arc)) as $a | $p | all(. as $x | $a | index($x)))
    and ((.aliases // {}) | type == "object")' <<<"$1" >/dev/null 2>&1
}

# edit <current-json> — print the road after this verb.
edit() {
  local cur="$1" a="${args[0]:-}" b="${args[1]:-}"
  case "$verb" in
    focus) jq --arg a "$a" --arg s "$summary" '
        (if (.arcs | any(.arc == $a)) then . else .arcs += [{arc: $a, summary: $s}] end)
        | (if $s != "" then .arcs |= map(if .arc == $a then .summary = $s else . end) else . end)
        | .pinned = ([$a] + ((.pinned // []) | map(select(. != $a))))
        | .aliases = ((.aliases // {}) | del(.[$a]))' <<<"$cur" ;;
    unpin) jq -e --arg a "$a" '.arcs | any(.arc == $a)' <<<"$cur" >/dev/null || die "'$a' is not on the road"
      jq --arg a "$a" '.pinned = ((.pinned // []) | map(select(. != $a)))' <<<"$cur" ;;
    add) jq -e --arg a "$a" '.arcs | any(.arc == $a)' <<<"$cur" >/dev/null && die "'$a' is already on the road"
      jq --arg a "$a" --arg s "$summary" '.arcs += [{arc: $a, summary: $s}] | .aliases = ((.aliases // {}) | del(.[$a]))' <<<"$cur" ;;
    drop) jq -e --arg a "$a" '.arcs | any(.arc == $a)' <<<"$cur" >/dev/null || die "'$a' is not on the road"
      jq --arg a "$a" '.arcs |= map(select(.arc != $a)) | .pinned = ((.pinned // []) | map(select(. != $a)))' <<<"$cur" ;;
    alias) [ "$a" != "$b" ] || die "an arc cannot alias itself"
      jq --arg a "$a" --arg b "$b" '
        .aliases = ((.aliases // {}) + {($a): (if $b == "-" then null else $b end)})
        | .arcs |= map(select(.arc != $a)) | .pinned = ((.pinned // []) | map(select(. != $a)))' <<<"$cur" ;;
    lanes) jq --argjson p "$a" --argjson s "$b" '.lanes = {primary: $p, secondary: $s}' <<<"$cur" ;;
  esac
}

authorized() {
  [ -f "$1/maintainers/allowlist" ] \
    && sed 's/#.*//; s/[[:space:]]//g' "$1/maintainers/allowlist" | grep -qxF "$2"
}

# GARDEN_ROAD_NO_SYNC=1 reads <DIR> as-is (a test seam; honored only by show and
# --dry-run, which never push).
no_sync=0
if [ "${GARDEN_ROAD_NO_SYNC:-0}" = 1 ] && { [ "$verb" = show ] || [ "$dry_run" -eq 1 ]; }; then no_sync=1; fi
[ "$no_sync" -eq 1 ] || { ensure_clone "$DIR"; sync_clone "$DIR"; }
if [ "$verb" = show ]; then road_show "$DIR"; exit 0; fi

[ -n "$authorized_by" ] || die "--authorized-by LOGIN (a maintainers/allowlist login) is required"
input=""
if [ "$verb" = init ] && [ "$from_slate" -eq 0 ]; then
  input="$(cat)"
  jq -e . >/dev/null 2>&1 <<<"$input" || die "init reads a road.json on stdin (or pass --from-slate)"
fi

for attempt in $(seq 1 "${GARDEN_POST_ATTEMPTS:-50}"); do
  [ "$attempt" -eq 1 ] || [ "$no_sync" -eq 1 ] || sync_clone "$DIR"
  authorized "$DIR" "$authorized_by" || die "'$authorized_by' is not on maintainers/allowlist; refusing"
  if [ "$verb" = init ]; then
    if [ "$from_slate" -eq 1 ]; then road="$(from_slate "$DIR")"; else road="$input"; fi
  else
    [ -f "$DIR/$ROAD" ] || die "no road yet; run 'set-road.sh init' first"
    road="$(edit "$(cat "$DIR/$ROAD")")"
  fi
  road="$(jq --arg auth "$authorized_by" --arg msg "$message_id" --arg note "$note" --arg by "$by" \
      --arg at "$(date -u +%FT%TZ)" '
      {schema: 1, lanes: (.lanes // {primary: 0.6, secondary: 0.4}), pinned: (.pinned // []),
       arcs: .arcs, aliases: (.aliases // {})}
      + {authorized_by: $auth, message_id: $msg, notes: $note, set_by: $by, set_at: $at}' <<<"$road")" \
    || die "could not build the road"
  validate "$road" || die "road rejected: lanes must sum to 1, arcs must be unique legal names, pinned arcs must be on the road"
  target="$DIR"
  if [ "$dry_run" -eq 1 ]; then
    target="$(mktemp -d "${TMPDIR:-/tmp}/set-road-dry.XXXXXX")"
    trap 'rm -rf "$target"' EXIT
  fi
  mkdir -p "$target/allocation"
  printf '%s\n' "$road" > "$target/$ROAD"
  render "$target"
  removed=()
  if [ "$verb" = init ]; then
    for f in config/apportionment config/foreman-mandate; do [ -f "$DIR/$f" ] && removed+=("$f"); done
    for f in "$DIR"/config/arc-budgets/*; do
      [ -f "$f" ] || continue
      jq -e '.schema == 2' "$f" >/dev/null 2>&1 && removed+=("config/arc-budgets/$(basename "$f")")
    done
  fi
  if [ "$dry_run" -eq 1 ]; then
    printf '== %s (dry run; nothing pushed) ==\n\n' "$ROAD"; cat "$target/$ROAD"
    printf '\n== allocation/mandate.md ==\n\n'; cat "$target/allocation/mandate.md"
    printf '\n== allocation/README.md ==\n\n'; cat "$target/allocation/README.md"
    if [ "$verb" = init ]; then
      printf '\n== removed in the same commit ==\n'
      [ "${#removed[@]}" -gt 0 ] && printf '  %s\n' "${removed[@]}" || printf '  (none)\n'
      printf '\n== the road after init (against the live board) ==\n'
      cp -r "$DIR/config" "$target/" 2>/dev/null || true
      for d in jobs usage budget maintainers; do [ -e "$DIR/$d" ] && ln -s "$DIR/$d" "$target/$d"; done
      for f in "${removed[@]}"; do rm -f "$target/$f"; done
      GARDEN_ROAD_STATE_WRITE=0 GARDEN_ROAD_CACHE_SECS=0 road_show "$target"
      printf '\nRollback after a real init: git revert <init-commit> on journal2 restores the slate files;\n'
      printf 'with no allocation/road.json the dormant code falls back to the ramp-and-cap behavior.\n'
    fi
    exit 0
  fi
  for f in ${removed[@]+"${removed[@]}"}; do git -C "$DIR" rm -q "$f"; done
  git -C "$DIR" add "$ROAD" allocation/mandate.md allocation/README.md
  rc=0; commit_and_push "$DIR" "road($verb${args[*]:+ ${args[*]}}) by $authorized_by" || rc=$?
  [ "$rc" -eq 0 ] && { log "road $verb applied"; road_show "$DIR"; exit 0; }
  [ "$rc" -eq 2 ] && { log "road unchanged"; exit 0; }
  backoff "$attempt"
done
die "could not apply road $verb"
